"""Recover unchanged gzip web assets from the pinned upstream C3 image.

Only portable HTTP content is extracted. No C3 executable code is reused.
Offsets and the whole-image hash deliberately bind this mapping to one image.
"""
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
IMAGE = ROOT.parent / "goldhen24b1812/bins/ESP32C3_XploitHost_600-1352.ino.bin"
IMAGE_SHA256 = "5d78672507ea2dd006c0b44787c0d475561ba2b6d4107f18d040d018f7e37b42"
# Route, gzip member file offset, original gzip filename, content type.
MEMBERS = [
    ("index.html", 0x119D70, "index.html", "text/html"),
    ("jb.html", 0x115F6C, "jb.html", "text/html"),
    ("logo_raw.png", 0xDB064, "logo_raw.png", "image/png"),
    ("core.js", 0xE7C84, "core.js", "application/javascript"),
    ("int64.js", 0xE79EC, "int64.js", "application/javascript"),
    ("jb.js", 0xE170C, "jb.js", "application/javascript"),
    ("mem.js", 0xDFE68, "mem.js", "application/javascript"),
    ("ps4_offsets.js", 0xDEF90, "ps4_offsets.js", "application/javascript"),
    ("rpc_worker.js", 0xDE85C, "rpc_worker.js", "application/javascript"),
    ("patches/1302.bin", 0xDAEA0, "1302.bin", "application/octet-stream"),
    ("patches/1350.bin", 0xDACD8, "1350.bin", "application/octet-stream"),
    ("patches/1352.bin", 0xDAB08, "1352.bin", "application/octet-stream"),
    ("goldhen.bin", 0x43176, "goldhen.bin", "application/octet-stream"),
    ("payload2.bin", 0x861CC, "payload2.bin", "application/octet-stream"),
    ("cache.appcache", 0x11EC20, "cache.appcache", "text/cache-manifest"),
]


def extract():
    image = IMAGE.read_bytes()
    if hashlib.sha256(image).hexdigest() != IMAGE_SHA256:
        raise ValueError("Upstream image changed; re-audit the asset offsets before building")
    generated = ROOT / "generated"
    generated.mkdir(exist_ok=True)
    lines = ["// Generated by scripts/extract_assets.py; do not edit.", "#pragma once"]
    records = []
    routes = []
    for i, (route, offset, filename, mime) in enumerate(MEMBERS):
        tail = image[offset:]
        if tail[:4] != b"\x1f\x8b\x08\x08":
            raise ValueError(f"Unexpected gzip header for {route}")
        if tail[10:].split(b"\0", 1)[0].decode() != filename:
            raise ValueError(f"Wrong gzip filename for {route}")
        decoder = zlib.decompressobj(31)
        raw = decoder.decompress(tail)
        if not decoder.eof:
            raise ValueError(f"Truncated gzip member: {route}")
        compressed = tail[:len(tail) - len(decoder.unused_data)]
        dest = generated / route
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(raw)
        packed = ROOT / "data" / "1302-1352" / (route + ".gz")
        packed.parent.mkdir(parents=True, exist_ok=True)
        packed.write_bytes(compressed)
        routes.append(f'  {{"/1302-1352/{route}", "{mime}", {len(compressed)}}},')
        records.append(dict(route="/1302-1352/" + route, offset=offset,
                            compressed_bytes=len(compressed), bytes=len(raw),
                            sha256=hashlib.sha256(raw).hexdigest()))
    lines += ["static const Asset assets[] = {", *routes, "};", ""]
    header = ROOT / "src/assets.generated.h"
    content = "\n".join(lines)
    if not header.exists() or header.read_text() != content:
        header.write_text(content)
    (generated / "asset-manifest.json").write_text(json.dumps(
        dict(source_sha256=IMAGE_SHA256, assets=records), indent=2) + "\n")
    print(f"Verified and extracted {len(records)} assets from pinned C3 image")


if __name__ == "__main__":
    extract()
